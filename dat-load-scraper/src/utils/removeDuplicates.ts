export const combinedExactAndSimilarLoadData = (dataDataObj:any) => {
    const similarMatchDetails = get(dataDataObj, ['similarMatchDetails'], [])
    const matchDetails = get(dataDataObj, ['matchDetails'], [])
    const combinedData = matchDetails.concat(similarMatchDetails)
    return combinedData
}

export const findDuplicates = (combinedData: any) => {
    let counts: any = {}
    // console.log("counts", counts)
    // const similarMatchDetails = get(dataDataObj, ['similarMatchDetails'], [])
    // const matchDetails = get(dataDataObj, ['matchDetails'], [])
    // const combinedData = matchDetails.concat(similarMatchDetails)

    for(let i =0; i < combinedData.length; i++){
        const datLoad = combinedData[i]
        const matchId = get(datLoad, ['matchId'], null);
        const companyName = get(datLoad, ['companyName'], "")
        const equipmentTypeCode = get(datLoad, ["equipmentTypeCode"], "")
        const loadWeight = get(datLoad, ["weight"], null);
        const loadLength = get(datLoad, ["length"], null);
        const originState = get(datLoad, ["origin", "state"], "");
        const originCity = get(datLoad, ["origin", "city"], "");
        const destinationState = get(datLoad, ["destination", "state"], "");
        const destinationCity = get(datLoad, ["destination", "city"], "");
        const formattedCompanyName = companyName.replaceAll(" ", "").toUpperCase()
        const formattedEquipmentTypeCode = equipmentTypeCode.toUpperCase()
        const formattedOriginState = originState.toUpperCase()
        const formattedOriginCity = originCity.toUpperCase()
        const formattedDestinationCity = destinationCity.toUpperCase()
        const formattedDestinationState = destinationState.toUpperCase()
        const key = `${formattedCompanyName}_${equipmentTypeCode}_${formattedOriginState}_${formattedOriginCity}_${formattedDestinationState}_${formattedDestinationCity}_${formattedEquipmentTypeCode}_${loadWeight}_${loadLength}`
        
        // console.log("Dup Key", key)
        
        if(counts[key]){
            const matchIdsArr = counts[key]['matchIds']
            counts[key]['matchIds'] = matchIdsArr.concat(matchId) 
            counts[key]['count'] += 1
        }else{
            counts[key] = {
                key,
                matchIds: [matchId],
                count: 1
            }
        }
    }
      
    return counts
} 

export const findDuplicatesId = (loadDataArr: any) => {
    let duplicatedMatchIds: any = [];
    const dupsResults = findDuplicates(loadDataArr)
    // console.log("dupsResults", dupsResults)

    for(let i in dupsResults){
        const datLoad = dupsResults[i]
        const loadCount = get(datLoad, ['count'], 0)
        const matchIDArr = get(datLoad, ['matchIds'], [])
        if(loadCount > 1){
            // console.log("matchIDArr", matchIDArr)
            // console.log("sliced Arr", matchIDArr.slice(1))
            const dupIds = matchIDArr.slice(1)
            duplicatedMatchIds = [...duplicatedMatchIds, ...dupIds]
        }
    }

    return duplicatedMatchIds
}


export const calculateMiniumAcceptableOffer = (loadObj, ratePerMile, additionalFee) => {
    const tripMiles = get(loadObj, ['tripMiles']);
    const rate = tripMiles * ratePerMile;
    const fee = rate * additionalFee;
    const miniumRate = rate + fee;
    return miniumRate
}

export const calculateLoadsMiniumAcceptableOffer = (loadArr: any, ratePerMile: number, additionalFee: number) => {
    const results = loadArr.map((load: any) => {
        const tripMiles = get(load, ['tripMiles']);
        const rate = tripMiles * ratePerMile;
        const fee = rate * additionalFee;
        const miniumRate = rate + fee;
        return({
            ...load,
            miniumRate: miniumRate
        })
    })
    return results
}

export const createLoadMap = (arr: any, key: string) => {
    return arr.reduce(function(acc: any, cur: any) {
        const objKey = cur[key]
        acc[objKey] = cur;
        return acc;
      }, {});
}


